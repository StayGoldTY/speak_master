  static LearningItem? byId(String id) {
    for (final item in items) {
      if (item.id == id) {
        return item;
      }
    }
    return null;
  }

  static List<LearningItem> forLesson(String lessonId) {
    return items
        .where((item) => item.sourceLessonIds.contains(lessonId))
        .toList();
  }
